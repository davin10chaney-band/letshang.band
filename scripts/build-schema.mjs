// Regenerates src/schema.js from migrations/*.sql so the Worker can set up its own database.
// Run after adding a migration:  node scripts/build-schema.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
const dir = new URL('../migrations/', import.meta.url);
const list = readdirSync(dir).filter((f) => f.endsWith('.sql')).sort().map((name) => ({
  name,
  statements: readFileSync(new URL(name, dir), 'utf8')
    .replace(/--[^\n]*/g, '')
    .split(';')
    .map((s) => s.replace(/\s+/g, ' ').trim())
    .filter(Boolean),
}));
writeFileSync(new URL('../src/schema.js', import.meta.url),
  '// Generated by scripts/build-schema.mjs from migrations/*.sql — do not edit by hand.\n' +
  'export const MIGRATIONS = ' + JSON.stringify(list, null, 1) + ';\n');
console.log(list.map((m) => `${m.name}: ${m.statements.length} statements`).join('\n'));
